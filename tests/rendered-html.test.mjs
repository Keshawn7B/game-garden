async function render() {
  const workerUrl = new URL("../dist/server/index.js", import.meta.url);
  workerUrl.searchParams.set("test", `${process.pid}-${Date.now()}`);
  const { default: worker } = await import(workerUrl.href);
  return worker.fetch(new Request("http://localhost/", { headers: { accept: "text/html" } }), { ASSETS: { fetch: async () => new Response("Not found", { status: 404 }) } }, { waitUntil() {}, passThroughOnException() {} });
}

test("server-renders the Game Garden hub", async () => {
  const response = await render();
  assert.equal(response.status, 200);
  assert.equal(response.headers.get("x-frame-options"), "DENY");
  assert.equal(response.headers.get("x-content-type-options"), "nosniff");
  assert.equal(response.headers.get("cross-origin-opener-policy"), "same-origin-allow-popups");
  assert.equal(response.headers.get("strict-transport-security"), "max-age=31536000; includeSubDomains");
  const contentSecurityPolicy = response.headers.get("content-security-policy") ?? "";
  assert.match(contentSecurityPolicy, /default-src 'self'/);
  assert.match(contentSecurityPolicy, /frame-ancestors 'none'/);
  assert.match(contentSecurityPolicy, /script-src 'nonce-[a-f0-9]{36}' 'strict-dynamic'/);
  const html = await response.text();
  const scriptTags = html.match(/<script\b[^>]*>/gi) ?? [];
  assert.ok(scriptTags.length > 0);
  assert.ok(scriptTags.every((tag) => /nonce="[a-f0-9]{36}"/.test(tag)));
  assert.match(html, /Game Garden/);
  assert.match(html, /Games/);
  assert.match(html, /ゲームガーデン/);
  assert.match(html, /ゲーム/);
  assert.doesNotMatch(html, /POCKET ARCADE|SMALL GAMES|HOW TO PLAY|ポケットアーケード/);
  assert.match(html, /Codebreaker/);
  assert.match(html, /Order Match/);
  assert.match(html, /Number Hunt/);
  assert.match(html, /Memory Flip/);
  assert.match(html, /Connect Four/);
  assert.match(html, /Battleship/);
  assert.match(html, /Dots &amp; Boxes/);
  assert.match(html, /Air Hockey/);
  assert.doesNotMatch(html, /Meducktion|Deducktion/);
  assert.match(html, /App navigation/);
  assert.match(html, /Ranks/);
  assert.match(html, /Profile/);
  assert.match(html, /og-game-garden\.png/);
  assert.doesNotMatch(html, /Pocket Play|POCKET PLAY|ポケットプレイ/);
  assert.doesNotMatch(html, /codex-preview|react-loading-skeleton|Your site is taking shape/i);
});

